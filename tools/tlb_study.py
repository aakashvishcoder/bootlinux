#!/usr/bin/env python3
"""TLB study: how Linux on RV32 uses the TLB, measured on the emulator.

Runs the emulator over a grid of configurations and workloads and writes
docs/results.md (tables) and docs/*.png (charts).

Every run boots Linux first. Because the emulator is deterministic (time is
derived from the instruction count), the boot portion of every run is
identical, so a workload's own cost is (boot + workload) - (boot alone),
computed per configuration.

Experiments
  1. TLB size sweep      4..128 entries, each workload
  2. ASIDs on vs off     the context-switch workload
  3. sfence.vma vs RAM   boot-time flushes for 32/64/128 MiB of RAM
  4. Superpages          stock kernel vs megapage-patched kernel, and a TLB
                         that cannot hold superpages (--split-superpages)
"""
import json
import os
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMU = os.path.join(ROOT, "build", "bootlinux")
DTS = os.path.join(ROOT, "dts", "bootlinux.dts")
WL = os.path.join(ROOT, "tests", "workloads")
DOCS = os.path.join(ROOT, "docs")
KERNELS = {"stock": os.path.join(ROOT, "build", "Image"),
           "megapages": os.path.join(ROOT, "build", "Image-megapages")}
WORKLOADS = ["memtouch", "pingpong", "primes"]
SIZES = [4, 8, 16, 32, 64, 128]

TMP = tempfile.mkdtemp(prefix="tlbstudy-")


def dtb_for(ram_mb):
    path = os.path.join(TMP, f"ram{ram_mb}.dtb")
    if not os.path.exists(path):
        src = open(DTS).read().replace("0x80000000 0x04000000",
                                       f"0x80000000 {ram_mb << 20:#010x}")
        subprocess.run(["dtc", "-q", "-I", "dts", "-O", "dtb", "-o", path, "-"],
                       input=src.encode(), check=True)
    return path


def run(kernel="stock", workload="boot", tlb=32, asid=9, split=False, ram=64):
    """Run one configuration; returns the stats dict."""
    tag = f"{kernel}-{workload}-{tlb}-{asid}-{int(split)}-{ram}"
    out = os.path.join(TMP, tag + ".json")
    cmd = [EMU, "--quiet", "--itlb", str(tlb), "--dtlb", str(tlb),
           "--asid-bits", str(asid), "--ram", str(ram), "--dtb", dtb_for(ram),
           "--script", os.path.join(WL, workload + ".txt"), "--stats", out]
    if split:
        cmd.append("--split-superpages")
    cmd.append(KERNELS[kernel])
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    with open(out) as f:
        return json.load(f)


def delta(full, boot):
    """Workload-only counters: (boot + workload) - boot."""
    return {k: full[k] - boot[k] for k in full if isinstance(full[k], (int, float))}


def mpki(d, key):
    """Misses per thousand instructions."""
    return 1000.0 * d[key] / d["instructions"] if d["instructions"] else 0.0


def run_grid(configs):
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 2) as ex:
        results = list(ex.map(lambda c: run(**c), configs))
    return {json.dumps(c, sort_keys=True): r for c, r in zip(configs, results)}


def key(**c):
    full = dict(kernel="stock", workload="boot", tlb=32, asid=9, split=False, ram=64)
    full.update(c)
    return json.dumps(full, sort_keys=True)


def main():
    for k, path in KERNELS.items():
        if not os.path.exists(path):
            sys.exit(f"missing {path}: build it with linux/build.sh {k}")
    os.makedirs(DOCS, exist_ok=True)

    configs = []
    def add(**c):
        full = dict(kernel="stock", workload="boot", tlb=32, asid=9, split=False, ram=64)
        full.update(c)
        if full not in configs:
            configs.append(full)

    for wl in ["boot"] + WORKLOADS:
        for size in SIZES:
            add(workload=wl, tlb=size)                         # experiment 1
        for kernel in KERNELS:
            for asid in (0, 9):
                add(workload=wl, asid=asid, kernel=kernel)     # experiment 2
        for kernel in KERNELS:
            for split in (False, True):
                add(workload=wl, kernel=kernel, split=split)   # experiment 4
    for ram in (32, 64, 128):
        add(ram=ram)                                           # experiment 3

    print(f"running {len(configs)} configurations...", file=sys.stderr)
    R = run_grid(configs)
    md = ["# TLB study results", "",
          "Generated by `tools/tlb_study.py`. MPKI = misses per 1000 instructions.",
          "Workload numbers exclude boot: (boot + workload) − (boot alone).", ""]
    data = {}

    # ---- 1. size sweep
    md += ["## 1. TLB size sweep (ITLB and DTLB both N entries, ASIDs on)", ""]
    md += ["| workload | " + " | ".join(f"{s}" for s in SIZES) + " |",
           "|---|" + "---|" * len(SIZES)]
    sweep = {}
    for wl in ["boot"] + WORKLOADS:
        row_d, row_i = [], []
        for s in SIZES:
            full = R[key(workload=wl, tlb=s)]
            d = full if wl == "boot" else delta(full, R[key(tlb=s)])
            row_d.append(mpki(d, "dtlb_misses"))
            row_i.append(mpki(d, "itlb_misses"))
        sweep[wl] = (row_d, row_i)
        md.append(f"| {wl} DTLB MPKI | " + " | ".join(f"{v:.2f}" for v in row_d) + " |")
        md.append(f"| {wl} ITLB MPKI | " + " | ".join(f"{v:.2f}" for v in row_i) + " |")
    data["sweep"] = sweep
    md.append("")

    # ---- 2. ASIDs
    md += ["## 2. ASIDs on vs off (32-entry TLBs)", "",
           "Without ASIDs, Linux flushes all non-global TLB entries on every "
           "address-space switch (`sfence.vma x0, <asid 0>`).", "",
           "| workload | kernel | ASIDs | DTLB MPKI | ITLB MPKI | page walks | switch flushes |",
           "|---|---|---|---|---|---|---|"]
    asid_rows = {}
    for wl in ["boot"] + WORKLOADS:
        for kernel in KERNELS:
            for asid in (9, 0):
                full = R[key(workload=wl, asid=asid, kernel=kernel)]
                d = full if wl == "boot" else delta(full, R[key(asid=asid, kernel=kernel)])
                walks = d["walks_fetch"] + d["walks_load"] + d["walks_store"]
                asid_rows[(wl, kernel, asid)] = d
                md.append(f"| {wl} | {kernel} | {'on' if asid else 'off'} | "
                          f"{mpki(d, 'dtlb_misses'):.2f} | {mpki(d, 'itlb_misses'):.2f} | "
                          f"{walks:,} | {d['flush_asid'] + d['flush_all']:,} |")
    data["asid"] = {f"{wl}/{k}/{a}": v for (wl, k, a), v in asid_rows.items()}
    md.append("")

    # ---- 3. sfence vs RAM
    md += ["## 3. Boot-time sfence.vma vs RAM size", "",
           "| RAM | single-page sfence.vma | 4 KiB pages of RAM | boot instructions |",
           "|---|---|---|---|"]
    for ram in (32, 64, 128):
        d = R[key(ram=ram)]
        md.append(f"| {ram} MiB | {d['flush_page']:,} | {(ram << 20) // 4096:,} | "
                  f"{d['instructions']:,} |")
    md.append("")

    # ---- 4. superpages
    md += ["## 4. Superpages (32-entry TLBs)", "",
           "Stock 6.12 maps RAM (the kernel's linear map) with 4 KiB pages on RV32; "
           "`megapages` applies `linux/rv32-linear-megapages.patch` to use 4 MiB pages. "
           "*split* = a TLB that caches every superpage as a 4 KiB entry.", "",
           "| workload | kernel | TLB | DTLB MPKI | ITLB MPKI | DTLB hits on 4 MiB pages | instructions |",
           "|---|---|---|---|---|---|---|"]
    sp = {}
    for wl in ["boot"] + WORKLOADS:
        for kernel in KERNELS:
            for split in (False, True):
                full = R[key(workload=wl, kernel=kernel, split=split)]
                d = full if wl == "boot" else delta(full, R[key(kernel=kernel, split=split)])
                sp[f"{wl}/{kernel}/{int(split)}"] = d
                share = 100.0 * d["dtlb_super_hits"] / d["dtlb_hits"] if d["dtlb_hits"] else 0
                md.append(f"| {wl} | {kernel} | {'split' if split else 'superpages'} | "
                          f"{mpki(d, 'dtlb_misses'):.2f} | {mpki(d, 'itlb_misses'):.2f} | "
                          f"{share:.1f}% | {d['instructions']:,} |")
    data["superpages"] = sp
    md.append("")

    with open(os.path.join(DOCS, "results.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(DOCS, "results.json"), "w") as f:
        json.dump(data, f, indent=1, default=str)
    plot(sweep, asid_rows, sp)
    print("\n".join(md))


def plot(sweep, asid_rows, sp):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(1, 2, figsize=(10, 4))
    floor = 0.005   # zero misses can't be drawn on a log axis
    for wl, (dm, im) in sweep.items():
        ax[0].plot(SIZES, [max(v, floor) for v in dm], marker="o", label=wl)
        ax[1].plot(SIZES, [max(v, floor) for v in im], marker="o", label=wl)
    for a, t in zip(ax, ["DTLB", "ITLB"]):
        a.set_xscale("log", base=2)
        a.set_yscale("log")
        a.set_ylim(floor * 0.8, 40)
        a.set_xticks(SIZES, [str(s) for s in SIZES])
        a.set_xlabel("TLB entries (fully associative, LRU)")
        a.set_ylabel("misses per 1000 instructions")
        a.set_title(f"{t} misses vs size (stock kernel)")
        a.grid(alpha=0.3)
    ax[0].legend()
    fig.tight_layout()
    fig.savefig(os.path.join(DOCS, "tlb_sweep.png"), dpi=130)

    fig, ax = plt.subplots(figsize=(7, 4))
    wls = ["boot"] + WORKLOADS
    bars = [("stock", 9, "stock kernel, ASIDs on"), ("stock", 0, "stock kernel, ASIDs off"),
            ("megapages", 9, "megapage kernel, ASIDs on"), ("megapages", 0, "megapage kernel, ASIDs off")]
    w = 0.2
    for i, (k, a, label) in enumerate(bars):
        vals = [mpki(asid_rows[(wl, k, a)], "dtlb_misses") + mpki(asid_rows[(wl, k, a)], "itlb_misses")
                for wl in wls]
        ax.bar([x + (i - 1.5) * w for x in range(len(wls))], vals, w, label=label)
    ax.set_xticks(list(range(len(wls))), wls)
    ax.set_ylabel("ITLB + DTLB misses per 1000 instructions")
    ax.set_title("ASIDs only pay off once the kernel stops thrashing the TLB")
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(DOCS, "asid.png"), dpi=130)
    plt.close("all")


if __name__ == "__main__":
    main()
